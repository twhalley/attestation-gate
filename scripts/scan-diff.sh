#!/usr/bin/env bash
# Measure, rather than assert, what the base image change is worth.
#
# Builds the same Python service two ways -- a conventional fat image and a
# Chainguard-based one -- then reports CVE counts, package counts and size for
# both. Writes a markdown table to stdout and to $GITHUB_STEP_SUMMARY when set.
#
# Requires: docker (or podman aliased to docker), grype, syft, jq.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BASELINE_TAG="attestation-gate/baseline:local"
HARDENED_TAG="attestation-gate/hardened:local"
OUT="${REPO_ROOT}/.scan"

# Podman by default: rootless and daemonless, so building an untrusted
# Dockerfile does not hand anything a socket equivalent to host root. Docker is
# still honoured if it is what you have.
# `podman info` rather than `command -v podman`: in a devcontainer the binary is
# frequently present but non-functional (nested user namespaces unavailable),
# and a fallback that only checks for the binary is not a fallback.
DOCKER="${DOCKER:-}"
if [ -z "$DOCKER" ]; then
  if command -v podman >/dev/null 2>&1 && podman info >/dev/null 2>&1; then
    DOCKER=podman
  elif command -v docker >/dev/null 2>&1; then
    DOCKER=docker
  else
    DOCKER=podman # fail below with a useful message rather than silently
  fi
fi

# Scan exported archives rather than the local image store. Reading Podman's
# store requires a running `podman system service` socket, which rootless
# installs do not have by default; the archive path needs no daemon at all and
# behaves identically under Docker in CI.
case "$(basename "$DOCKER")" in
  podman) SAVE_FORMAT="oci-archive"    ; SCHEME="oci-archive:"    ;;
  *)      SAVE_FORMAT="docker-archive" ; SCHEME="docker-archive:" ;;
esac

for bin in "$DOCKER" grype syft jq; do
  command -v "$bin" >/dev/null 2>&1 || { echo "missing required tool: $bin" >&2; exit 1; }
done

mkdir -p "$OUT"
log() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }

log "building baseline image (python:3.12, pip as root, no venv)"
"$DOCKER" build -q -f "${REPO_ROOT}/baseline/Dockerfile" -t "$BASELINE_TAG" "$REPO_ROOT" >/dev/null

log "building hardened image (cgr.dev/chainguard/python, non-root, venv)"
"$DOCKER" build -q -f "${REPO_ROOT}/app/Dockerfile" -t "$HARDENED_TAG" "${REPO_ROOT}/app" >/dev/null

scan() {
  local tag="$1" name="$2"
  local archive="${OUT}/${name}.tar"

  log "exporting ${name}"
  rm -f "$archive"
  if [ "$SAVE_FORMAT" = "oci-archive" ]; then
    "$DOCKER" save --format oci-archive -o "$archive" "$tag"
  else
    "$DOCKER" save -o "$archive" "$tag"
  fi

  log "scanning ${name}"
  grype "${SCHEME}${archive}" -o json --quiet > "${OUT}/${name}.grype.json"
  syft  "${SCHEME}${archive}" -o syft-json --quiet > "${OUT}/${name}.syft.json"
  rm -f "$archive"
}

scan "$BASELINE_TAG"  baseline
scan "$HARDENED_TAG"  hardened

sev_count() { # file severity
  jq --arg s "$2" '[.matches[] | select(.vulnerability.severity == $s)] | length' "$1"
}
total_count() { jq '.matches | length' "$1"; }
pkg_count()   { jq '.artifacts | length' "$1"; }
size_bytes()  { "$DOCKER" image inspect "$1" --format '{{.Size}}'; }

human() { numfmt --to=iec --suffix=B "$1" 2>/dev/null || echo "${1}B"; }

delta() { # before after
  local b="$1" a="$2"
  if [ "$b" -eq 0 ]; then echo "—"; return; fi
  local pct=$(( (b - a) * 100 / b ))
  echo "-${pct}%"
}

B_TOTAL=$(total_count "${OUT}/baseline.grype.json")
H_TOTAL=$(total_count "${OUT}/hardened.grype.json")
B_PKGS=$(pkg_count "${OUT}/baseline.syft.json")
H_PKGS=$(pkg_count "${OUT}/hardened.syft.json")
B_SIZE=$(size_bytes "$BASELINE_TAG")
H_SIZE=$(size_bytes "$HARDENED_TAG")

report() {
  echo "## Base image comparison"
  echo
  echo "Same application and the same pinned dependencies, two base images."
  echo "Generated by \`scripts/scan-diff.sh\` on every run — not typed by hand."
  echo
  echo "| Metric | Baseline (\`python:3.12\`) | Hardened (\`cgr.dev/chainguard/python\`) | Change |"
  echo "|---|---:|---:|---:|"
  for sev in Critical High Medium Low Negligible Unknown; do
    b=$(sev_count "${OUT}/baseline.grype.json" "$sev")
    h=$(sev_count "${OUT}/hardened.grype.json" "$sev")
    [ "$b" -eq 0 ] && [ "$h" -eq 0 ] && continue
    echo "| ${sev} CVEs | ${b} | ${h} | $(delta "$b" "$h") |"
  done
  echo "| **Total CVEs** | **${B_TOTAL}** | **${H_TOTAL}** | **$(delta "$B_TOTAL" "$H_TOTAL")** |"
  echo "| Packages in SBOM | ${B_PKGS} | ${H_PKGS} | $(delta "$B_PKGS" "$H_PKGS") |"
  echo "| Image size | $(human "$B_SIZE") | $(human "$H_SIZE") | $(delta "$B_SIZE" "$H_SIZE") |"
  echo
  echo "> Both images contain the same interpreter and the same third-party packages, so the"
  echo "> hardened count is not zero and should not be. What the base image removes is the"
  echo "> surrounding distribution: shell, package manager, compiler toolchain, setuid binaries."
  echo "> That is a smaller attack surface, not a safer application — a bug in \`app.py\`, or a"
  echo "> vulnerable version of Flask, is equally exploitable in both."
}

echo
report
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
  report >> "$GITHUB_STEP_SUMMARY"
  report > "${OUT}/report.md"
fi
